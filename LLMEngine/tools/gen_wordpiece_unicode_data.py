#!/usr/bin/env python3
# ============================================================================
# gen_wordpiece_unicode_data.py — genera native/gmb_runtime_c/src/gmb_wp_unicode_data.inc
#
# Uso: python3 tools/gen_wordpiece_unicode_data.py [--check]
#   (default)  rigenera il file include in native/gmb_runtime_c/src/.
#   --check    exit 1 se il file include divergerebbe (gate CI), exit 0 se identico.
#
# Fonte dati: unicodedata (questo interpreter usa Unicode 16.0.0, lo standard
# anche del runtime .NET 10 target del progetto) — NON una dipendenza runtime:
# lo script produce un file C autosufficiente e versionato; il runtime non ha
# nessun legame con Python. --check permette di rilevare drift se la versione
# Unicode dell'ambiente cambia.
#
# Contratto col C# (BertWordPieceTokenizer.cs, parita' di comportamento):
#   BasicTokenize: clean (C* eccetto \t\n\r), Zs -> spazio, NFD + scarta Mn,
#   lowercase, split punteggiatura P* o range ASCII, isolamento ideogrammi CJK.
#   WordPiece: greedy longest-match, prefisso "##", fallimento = [UNK] intera parola.
# ============================================================================
import argparse
import sys
import unicodedata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "native" / "gmb_runtime_c" / "src" / "gmb_wp_unicode_data.inc"

UNI_VERSION = unicodedata.unidata_version

CAT_CLEAN_DROP = {"Cc", "Cf", "Co", "Cn"}
CAT_SPACE = {"Zs"}
CAT_MN = {"Mn"}
CAT_PUNCT = {"Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Pc"}


def canon_decomp(cp: int):
    ch = chr(cp)
    nd = unicodedata.normalize("NFD", ch)
    if len(nd) == 1 and ord(nd) == cp:
        return None
    return tuple(ord(x) for x in nd)


def collapse_ranges(items):
    if not items:
        return []
    items = sorted(items)
    out = [list(items[0])]
    for s, e in items[1:]:
        if s <= out[-1][1] + 1:
            out[-1][1] = max(out[-1][1], e)
        else:
            out.append([s, e])
    return [(a, b) for a, b in out]


def collect():
    clean, space, mn, punct = [], [], [], []
    lower, decomp = {}, {}

    for cp in range(0x110000):
        try:
            ch = chr(cp)
            cat = unicodedata.category(ch)
        except Exception:
            continue
        if cat in CAT_CLEAN_DROP:
            clean.append((cp, cp))
        elif cat in CAT_SPACE:
            space.append((cp, cp))
        elif cat in CAT_MN:
            mn.append((cp, cp))
        elif cat in CAT_PUNCT:
            punct.append((cp, cp))

        d = canon_decomp(cp)
        if d is not None:
            decomp[cp] = d

        lo = chr(cp).lower()
        if lo != ch:
            lower[cp] = tuple(ord(x) for x in lo)

    return {
        "clean": collapse_ranges(clean),
        "space": collapse_ranges(space),
        "mn": collapse_ranges(mn),
        "punct": collapse_ranges(punct),
        "lower": lower,
        "decomp": decomp,
    }


def emit(obj):
    L = []
    L.append("/* AUTO-GENERATED by tools/gen_wordpiece_unicode_data.py -- DO NOT EDIT BY HAND. */")
    L.append("/* Unicode %s (matcha dal runtime .NET 10 target). Rigenera con:" % UNI_VERSION)
    L.append(" *   python3 tools/gen_wordpiece_unicode_data.py")
    L.append(" * Tabelle in intervalli di codepoint + mappe punto-punto lowercase/NFD. */")
    L.append("")
    L.append("#ifndef GMB_WP_UNICODE_DATA_INC")
    L.append("#define GMB_WP_UNICODE_DATA_INC")
    L.append("")
    L.append("typedef struct { unsigned a, b; } gmb_wp_range_t;")
    L.append("")

    for key, name in [("clean", "gmb_wp_clean_ranges"), ("space", "gmb_wp_space_ranges"),
                       ("mn", "gmb_wp_mn_ranges"), ("punct", "gmb_wp_punct_ranges")]:
        rs = obj[key]
        L.append("static const gmb_wp_range_t %s[] = {" % name)
        for a, b in rs:
            L.append("    {0x%X, 0x%X}," % (a, b))
        L.append("};")
        L.append("#define %s_COUNT %d" % (name.upper(), len(rs)))
        L.append("")

    lv = sorted(obj["lower"].items())
    lmax = max((len(p) for p in [v for _, v in lv]), default=1)
    lcols = 2 + lmax
    L.append("/* Lowercase Unicode (espansioni punto-punto, anche multi-parte): {cp, n_parts, p0, ...}. */")
    L.append("#define GMB_WP_LOWER_MAX_PARTS %d" % lmax)
    L.append("static const unsigned gmb_wp_lower_map[][%d] = {" % lcols)
    for cp, parts in lv:
        row = [cp, len(parts)] + list(parts) + [0] * (lmax - len(parts))
        L.append("    {%s}," % ", ".join("0x%X" % v for v in row))
    L.append("};")
    L.append("#define GMB_WP_LOWER_MAP_COUNT %d" % len(lv))
    L.append("")

    dv = sorted(obj["decomp"].items())
    maxparts = max((len(parts) for _, parts in dv), default=1)
    cols = 2 + maxparts
    L.append("/* NFD canonico: ogni riga {cp, n_parts, p0, p1, ...} (max %d parti). */" % maxparts)
    L.append("#define GMB_WP_NFD_MAX_PARTS %d" % maxparts)
    L.append("static const unsigned gmb_wp_nfd_map[][%d] = {" % cols)
    for cp, parts in dv:
        row = [cp, len(parts)] + list(parts) + [0] * (maxparts - len(parts))
        L.append("    {%s}," % ", ".join("0x%X" % v for v in row))
    L.append("};")
    L.append("#define GMB_WP_NFD_MAP_COUNT %d" % len(dv))
    L.append("")
    L.append("#endif /* GMB_WP_UNICODE_DATA_INC */")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 se il file divergerebbe")
    args = ap.parse_args()

    obj = collect()
    text = emit(obj) + "\n"

    if args.check:
        if OUT.exists() and OUT.read_text() == text:
            print("unicode data OK (%d clean, %d space, %d mn, %d punct, %d lower, %d nfd)"
                  % (len(obj["clean"]), len(obj["space"]), len(obj["mn"]), len(obj["punct"]),
                     len(obj["lower"]), len(obj["decomp"])))
            return 0
        print("MISMATCH: gmb_wp_unicode_data.inc non e' allineato "
              "(rigenerare con gen_wordpiece_unicode_data.py)", file=sys.stderr)
        return 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    sz = OUT.stat().st_size
    print("generato %s (%d clean, %d space, %d mn, %d punct, %d lower, %d nfd, %d bytes)"
          % (OUT, len(obj["clean"]), len(obj["space"]), len(obj["mn"]), len(obj["punct"]),
             len(obj["lower"]), len(obj["decomp"]), sz))
    return 0


if __name__ == "__main__":
    sys.exit(main())
